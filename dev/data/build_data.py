"""Convert the Airtable CSV exports in this folder into radar-data.js.

Keep the CSVs fresh with sync_airtable.py (automatic), or re-export the views
from Airtable by hand over the CSVs here. Then run:
    python build_data.py
"""
import csv
import json
import re
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).parent


def rows(name):
    with open(HERE / name, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def clean(text):
    return re.sub(r"\s+", " ", (text or "")).strip()


def split_list(cell):
    """Split an Airtable multi-value cell; items containing commas are quoted."""
    cell = (cell or "").strip()
    if not cell:
        return []
    items = next(csv.reader([cell], skipinitialspace=True))
    return [clean(i).strip('"').strip() for i in items if clean(i)]


def unique(items):
    return list(dict.fromkeys(items))


def audience(cell):
    return [a.replace("inc..", "incl.") for a in split_list(cell)]


def url(cell):
    cell = clean(cell)
    return cell if cell.startswith(("http://", "https://")) else ""


def iso_date(cell):
    """Airtable exports m/d/yyyy; the API returns yyyy-mm-dd."""
    cell = clean(cell)
    for fmt in ("%Y-%m-%d", "%m/%d/%Y"):
        try:
            return datetime.strptime(cell, fmt).date().isoformat()
        except ValueError:
            pass
    return ""


def build():
    services_by_resource = {}
    for r in rows("what-we-offer.csv"):
        resource = clean(r["Linked AI Resource(s)"]).strip('"')
        services_by_resource.setdefault(resource, []).append({
            "type": clean(r["Service Type"]),
            "status": clean(r["Availability Status"]),
            "description": clean(r["Description"]),
            "primary": split_list(r["Primary contact"]),
            "secondary": split_list(r["Secondary contact"]),
            "other": split_list(r["Other Contacts"]),
            "workshops": unique(split_list(r["Workshop catalog"])),
        })

    resources = []
    for r in rows("ai-resources.csv"):
        name = clean(r["Resource Name"]).strip('"')
        resources.append({
            "name": name,
            "type": clean(r["Type"]),
            "availability": clean(r["Availability"]),
            "audience": audience(r["Supported Audience"]),
            "contacts": split_list(r["Points of Contact Map"]),
            "url": url(r["Website / Access URL"]),
            "docs": url(r["Documentation (Attachment)"]),
            "services": services_by_resource.get(name, []),
        })

    people = [{
        "name": clean(r["Person"]),
        "email": clean(r["Email"]),
        "title": clean(r["Title"]),
        "department": clean(r["Department"]),
        "expertise": split_list(r["AI Expertise"]),
        "workshops": unique(split_list(r["Workshops offered"])),
    } for r in rows("points-of-contact.csv")]

    # The "Notes" column is internal staff scratch space and is deliberately not published.
    # "Materials (attached)" is skipped too: Airtable attachment links expire within hours.
    workshops = [{
        "name": clean(r["Name"]),
        "status": clean(r["Status"]),
        "lastOffered": iso_date(r["Last offered"]),
        "owners": split_list(r["Owners"]),
        "resources": unique(split_list(r["Linked AI Resource(s) (from Offering)"])),
        "materials": url(r["Materials URL"]),
    } for r in rows("workshop-catalog.csv")]

    unmatched = set(services_by_resource) - {r["name"] for r in resources}
    if unmatched:
        raise SystemExit(f"Services linked to unknown resources: {sorted(unmatched)}")

    data = {"resources": resources, "people": people, "workshops": workshops}
    (HERE / "radar-data.js").write_text(
        "// Generated by build_data.py from the Airtable CSV exports. Do not edit by hand.\n"
        "window.RADAR_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(resources)} resources, {sum(len(r['services']) for r in resources)} services, "
          f"{len(people)} people, {len(workshops)} workshops")


if __name__ == "__main__":
    build()
